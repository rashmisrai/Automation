# Strings in Python

str1 = "Hello, World!"
print(str1)

str2 = "Rashmi"
print(str2)

print(str1 + " " + str2)  # Concatenation
print(str1[0])  # Indexing
print(str1[0:5])  # Slicing
print(str1[:5])
print(len(str2))  # Length of the string
print(str1.lower())  # Convert to lowercase
print(str1.upper())  # Convert to uppercase
print(str1.replace("World", "Python"))  # Replace substring
